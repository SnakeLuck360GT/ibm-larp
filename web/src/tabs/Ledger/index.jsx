async function getJSON(url) {
  const r = await fetch(url, { cache: 'no-store' })
  if (!r.ok) throw new Error(`${r.status} ${url}`)
  return r.json()
}

function linkify(text) {
  const parts = String(text).split(/(https?:\/\/[^\s)]+)/g)
  return parts.map((p, i) => /^https?:\/\//.test(p) ? <a key={i} href={p} target="_blank" rel="noreferrer">{p}</a> : p)
}

const num3 = x => Number(x).toLocaleString('en-MY', { maximumFractionDigits: 3 })

function Q({ src }) {
  const q = quality(src)
  if (q === 'sourced') return null
  return <span className={`ledger-q ${q}`}>{q === 'placeholder' ? 'Placeholder' : 'Approximate'}</span>
}

