/* HazeGuard-MY · Cross-border ledger tab.

   "Where did it come from, and what did it cost?"
   Data (all generated by the pipeline, nothing typed in):
     data/damage.json   pipeline/04_policy.py: damage to date, 72 h best/expected/worst, Monte Carlo,
                        sensitivity, backtest, every assumption with its source
     data/states.json   pipeline/03_equity.py: haze priority + allocation, to link cost to vulnerability (optional)
     data/attribution.json  web/src/tabs/Ledger/build_attribution.py: Sep 2019 smoke source shares by province
                        (ERA5 100 m back-trajectories x NASA FIRMS VIIRS hotspots) (optional)
     data/ledger_brief.json pipeline/ledger_brief.py: AI decision brief written by an LLM on Groq from the files above (optional)
   Props: { baseUrl, horizon: '24'|'48'|'72', setHorizon, stKey, select }
*/
import { useEffect, useMemo, useState } from 'react'
import {
  HeroRange, RangeTrack, niceMax,
} from './charts.jsx'
import {
  KEY, SCEN, SECTOR, SECTORS, cleanSource, coefLabel, dlong, nf, pct, quality, rm, short,
} from './format.js'
import { AttributionMethod, AttributionSection } from './Attribution.jsx'
import './ledger.css'

const BAND_LABEL = { moderate: 'Moderate (API 51–100)', unhealthy: 'Unhealthy (101–200)', very_unhealthy: 'Very unhealthy (201–300)', hazardous: 'Hazardous (300+)' }

async function getJSON(url) {
  const r = await fetch(url, { cache: 'no-store' })
  if (!r.ok) throw new Error(`${r.status} ${url}`)
  return r.json()
}

function linkify(text) {
  const parts = String(text).split(/(https?:\/\/[^\s)]+)/g)
  return parts.map((p, i) => /^https?:\/\//.test(p) ? <a key={i} href={p} target="_blank" rel="noreferrer">{p}</a> : p)
}

const num3 = x => Number(x).toLocaleString('en-MY', { maximumFractionDigits: 3 })

function Q({ src }) {
  const q = quality(src)
  if (q === 'sourced') return null
  return <span className={`ledger-q ${q}`}>{q === 'placeholder' ? 'Placeholder' : 'Approximate'}</span>
}

export default function LedgerTab({ baseUrl = '/', horizon = '24', setHorizon, stKey, select }) {
  const [dmg, setDmg] = useState(null)
  const [err, setErr] = useState(null)
  const [eq, setEq] = useState(null)
  const [att, setAtt] = useState(null)
  const [brief, setBrief] = useState(null)
  const [scen, setScen] = useState('expected')
  const [localSel, setLocalSel] = useState(null)
  const sel = stKey !== undefined && select ? stKey : localSel
  const pick = k => (select ? select(k) : setLocalSel(k))

  useEffect(() => {
    let live = true
    getJSON(`${baseUrl}data/damage.json`).then(j => live && setDmg(j)).catch(e => live && setErr(e.message))
    getJSON(`${baseUrl}data/states.json`).then(j => live && setEq(j)).catch(() => {})
    getJSON(`${baseUrl}data/attribution.json`).then(j => live && setAtt(j)).catch(() => {})
    getJSON(`${baseUrl}data/ledger_brief.json`).then(j => live && setBrief(j)).catch(() => {})
    return () => { live = false }
  }, [baseUrl])

  const v = useMemo(() => dmg && derive(dmg, eq), [dmg, eq])

  if (err) return (
    <div className="ledger-root"><div className="card ledger-empty" role="alert">
      <b>Damage estimate not available.</b> Could not load <span className="mono">data/damage.json</span> ({err}).
      Run <span className="mono">python pipeline/04_policy.py</span> from the repo root.
    </div></div>
  )
  if (!v) return <div className="ledger-root"><div className="card ledger-empty" aria-busy="true">Loading the damage estimate…</div></div>

  const sc = v.scen

  return (
    <div className="ledger-root">
      {/* ======== 1. The cost, as a range ======== */}
      <section className="card ledger-hero" aria-labelledby="ledger-hero-h">
        <div className="ledger-hero-main">
          <div className="label" id="ledger-hero-h">Estimated damage to Malaysia, next 72 hours</div>
          <p className="ledger-big num">
            {rm(sc.best.total_72h_rm)} <span className="ledger-big-to">to</span> {rm(sc.worst.total_72h_rm)}
          </p>
          <p className="ledger-sub">
            Expected <b className="num">{rm(sc.expected.total_72h_rm)}</b> · <b className="num">{rm(sc.expected.total_72h_rm / 3)}</b>/day ·
            worst over {sc.worst.affected_days} days <b className="num">{rm(sc.worst.if_prolonged_rm)}</b>
          </p>
          <HeroRange best={sc.best.total_72h_rm} expected={sc.expected.total_72h_rm} worst={sc.worst.total_72h_rm}
            bench={v.bench72} scen={scen} setScen={setScen} />
          <div className="ledger-scen" role="radiogroup" aria-label="Scenario shown in the breakdowns below">
            {SCEN.map(s => (
              <button key={s.k} type="button" role="radio" aria-checked={scen === s.k} className={`ledger-scen-b ${s.k}`}
                onClick={() => setScen(s.k)}>
                <span className="ledger-scen-t"><i className="ledger-rb" />{s.label}<b className="num">{rm(sc[s.k].total_72h_rm)}</b></span>
              </button>
            ))}
          </div>
        </div>
        <div className="ledger-hero-side">
          <div className="label">So far this episode</div>
          <p className="ledger-mid num">{rm(v.nat.total_damage_rm)}</p>
          <p className="ledger-sub">{dlong(dmg.episode.start)} to {dlong(dmg.episode.end)} · {dmg.episode.days} days</p>
          <dl className="ledger-kv">
            <div><dt>90% range</dt><dd className="num">{rm(v.nat.ci90_rm[0])} – {rm(v.nat.ci90_rm[1])}</dd></div>
            <div><dt>Per day</dt><dd className="num">{rm(v.nat.damage_per_day_rm)}</dd></div>
            <div><dt>Published estimate</dt><dd className="num">RM 20–50 m a day</dd></div>
          </dl>
          <span className={`ledger-flag ${v.inBench ? 'ok' : 'warn'}`}><i aria-hidden="true" />{v.inBench ? 'Within' : 'Outside'} published RM 20–50 m/day</span>
        </div>
        <div className="ledger-hero-foot">
          <span className={`ledger-flag ${v.persist ? 'warn' : 'ok'}`}>
            <i aria-hidden="true" />{v.persist ? 'PM2.5 next 72 h: last 3 days held flat' : 'PM2.5 next 72 h: forecast model'}
          </span>
          <span className="ledger-flag"><i aria-hidden="true" />Estimate</span>
          <span className="ledger-flag"><i aria-hidden="true" />Placeholder inputs: {v.nPlace} of {v.nAssume}</span>
        </div>
      </section>

      {brief && brief.headline && <Brief b={brief} />}

      {/* ======== 2. Where it came from ======== */}
      <section className="card ledger-src" aria-labelledby="ledger-src-h">
        <div className="card-h"><h3 id="ledger-src-h">Where the smoke came from</h3>
          <span className="ledger-src-tags">
            <span className="ledger-flag ok"><i aria-hidden="true" />Sep 2019 haze</span>
            <span className="ledger-flag"><i aria-hidden="true" />Provinces only, no companies</span>
          </span></div>
        {att ? <AttributionSection att={att} sel={sel} pick={pick} /> : (
          <p className="hint ledger-src-none">Source shares not loaded (data/attribution.json).</p>
        )}
      </section>

      {/* ======== 3. Who pays: states ======== */}
      <section className="card" aria-labelledby="ledger-st-h">
        <div className="card-h">
          <h3 id="ledger-st-h">Who pays: all states ranked by damage, next 72 hours</h3>
          <div className="ledger-key hint" aria-hidden="true">
            <span><i className="ledger-key-rng" />best to worst case</span>
            <span><i className="ledger-key-mid" />{SCEN.find(s => s.k === scen).label.toLowerCase()}</span>
          </div>
        </div>
        <div className="ledger-rows" role="list" aria-label="States ranked by damage">
            <div className="ledger-row ledger-row-h" aria-hidden="true">
              <span>State</span><span>Range, next 72 h</span><span className="r">{SCEN.find(s => s.k === scen).label}</span>
              <span className="r" title="Haze priority from Resource routing (1 = help first)">Priority</span>
            </div>
            {[...v.statesSorted].sort((a, b) => b.forecast_72h_scenarios_rm[scen] - a.forecast_72h_scenarios_rm[scen]).map((s, i) => {
              const k = KEY[s.state]
              const on = k === sel
              const r = s.forecast_72h_scenarios_rm
              const p = v.prio[s.state]
              return (
                <button type="button" role="listitem" key={s.state} className={`ledger-row${on ? ' on' : ''}`}
                  aria-pressed={on} onClick={() => pick(k)}
                  aria-label={`${i + 1}. ${short(s.state)}: ${rm(r[scen])} ${scen}, range ${rm(r.best)} to ${rm(r.worst)}${p ? `, haze priority ${p.priority}` : ''}`}>
                  <span className="ledger-row-n"><span className="ledger-row-rk num">{i + 1}</span>{short(s.state)}</span>
                  <RangeTrack lo={r.best} mid={r[scen]} hi={r.worst} max={v.stMax} />
                  <span className="ledger-row-v num">{rm(r[scen])}</span>
                  <span className={`ledger-row-p mono${p && p.priority <= 5 ? ' hot' : ''}`}>{p ? '#' + p.priority : '–'}</span>
                </button>
              )
            })}
        </div>
      </section>

      {/* ======== 4. By sector ======== */}
      <section className="card" aria-labelledby="ledger-sec-h">
        <div className="card-h">
          <h3 id="ledger-sec-h">What it costs: by sector</h3>
          <span className="hint">Next 72 h and so far</span>
        </div>
        <div className="ledger-sec">
          <div className="ledger-row ledger-row-h ledger-sec-r" aria-hidden="true">
            <span>Sector</span><span>Range, next 72 h</span><span className="r">{SCEN.find(s => s.k === scen).label}</span><span className="r">So far</span>
          </div>
          {v.sectorRows.map(r => (
            <div className="ledger-row ledger-sec-r" key={r.k} role="group"
              aria-label={`${r.label}: next 72 hours ${rm(r[scen])} (${rm(r.best)} to ${rm(r.worst)}); so far ${rm(r.sofar)}`}>
              <span className="ledger-row-n"><i className="ledger-sw" style={{ background: r.c }} />{r.label}</span>
              <RangeTrack lo={r.best} mid={r[scen]} hi={r.worst} max={v.secMax} />
              <span className="ledger-row-v num">{rm(r[scen])}</span>
              <span className="ledger-row-v num muted">{rm(r.sofar)} <small>{pct(r.sofar / v.nat.total_damage_rm)}</small></span>
            </div>
          ))}
        </div>
      </section>

      {/* ======== 7. Assumptions ======== */}
      <Assumptions dmg={dmg} v={v} att={att} />
    </div>
  )
}

/* ---------- AI decision brief (pipeline/ledger_brief.py: an LLM on Groq words it from this page's data) ---------- */
function Brief({ b }) {
  return (
    <section className="card ledger-ai" aria-labelledby="ledger-ai-h">
      <div className="card-h">
        <h3 id="ledger-ai-h">AI decision brief</h3>
      </div>
      <div className="ledger-ai-b">
        <p className="ledger-ai-head">{b.headline}</p>
        <p>{b.summary}</p>
        {b.actions && b.actions.length > 0 && (
          <ol className="ledger-ai-act" aria-label="Suggested decisions">
            {b.actions.map((a, i) => <li key={i}>{a}</li>)}
          </ol>
        )}
        <p className="hint">AI-written from the figures on this page; every number is checked against them before it is shown. Suggestions, not orders: check before acting.</p>
      </div>
    </section>
  )
}

/* ---------- derived view model ---------- */
function derive(dmg, eq) {
  const scen = dmg.forecast_72h.scenarios
  const nat = dmg.national
  const states = dmg.states
  const stateBy = Object.fromEntries(states.map(s => [s.state, s]))
  const statesSorted = [...states].sort((a, b) => b.forecast_72h_scenarios_rm.expected - a.forecast_72h_scenarios_rm.expected)
  const stMax = niceMax(Math.max(...states.map(s => s.forecast_72h_scenarios_rm.worst)) * 1.02)
  const sectorRows = SECTORS.map(s => ({
    ...s, best: scen.best.by_sector_rm[s.k], expected: scen.expected.by_sector_rm[s.k], worst: scen.worst.by_sector_rm[s.k],
    sofar: nat.by_category_rm[s.k],
  })).sort((a, b) => b.expected - a.expected)
  const secMax = niceMax(Math.max(...sectorRows.map(r => r.worst)) * 1.02)
  const prio = {}
  if (eq && eq.states) for (const s of eq.states) prio[s.state] = s
  const b = dmg.model.benchmark_rm_per_day
  const persist = /persistence/i.test(dmg.forecast_72h.source || '')
  const nAssume = dmg.assumptions.length
  const nPlace = dmg.assumptions.filter(a => quality(a.source) === 'placeholder').length
  return {
    scen, nat, stateBy, statesSorted, stMax, sectorRows, secMax, prio, persist, nAssume, nPlace,
    bench72: b ? [b[0] * 3, b[1] * 3] : null,
    inBench: b ? nat.damage_per_day_rm >= b[0] && nat.damage_per_day_rm <= b[1] : false,
  }
}

/* ---------- assumptions ---------- */
function Assumptions({ dmg, v, att }) {
  const coef = dmg.assumptions.filter(a => Array.isArray(a.range))
  const rates = dmg.loss_rates || {}
  const other = dmg.assumptions.filter(a => !Array.isArray(a.range) && !/^loss_rate_/.test(a.name))
  const nApprox = dmg.assumptions.filter(a => quality(a.source) === 'approx').length
  const fmtV = a => {
    if (typeof a.value === 'number') return num3(a.value)
    return a.value === '' ? '—' : String(a.value)
  }
  return (
    <details className="card ledger-assume">
      <summary>
        <span><b>Assumptions and sources</b>
          <span className="hint"> · placeholder inputs: {v.nPlace} of {v.nAssume} · approximate: {nApprox}</span></span>
        <span className="ledger-assume-cta hint" aria-hidden="true">Show</span>
      </summary>
      <div className="ledger-assume-body">
        <p className="ledger-formula mono">{dmg.method}</p>
        <h4>Method notes</h4>
        <ul className="ledger-list hint">
          <li>Damage = daily value of the sector × share lost at that day's haze level × share of the state affected.</li>
          <li>{v.persist ? 'PM2.5 for the next 72 h: the last 3 days held flat (the damage model did not use the forecast model output).' : `PM2.5 for the next 72 h: forecast model (${dmg.forecast_72h.source}).`} An estimate, re-run with the pipeline, not a live counter.</li>
          <li>Outside check: economists put the 2026 haze at RM 20–50 m a day (Dr Yeah Kim Leng, The Star, 14 Oct 2026); our daily rate sits {v.inBench ? 'inside' : 'outside'} that range.</li>
          <li>Not counted: school closures {rm(v.nat.memo_not_in_total_rm.school_closure)}, cloud seeding {rm(v.nat.memo_not_in_total_rm.response)} (they overlap the sectors or are public spending), and deaths (haze treated as non-fatal).</li>
          <li>Monte Carlo: {nf(dmg.model.n_sims)} runs, each redrawing every loss rate and cost within its range; 90% of runs land in the range shown in the header.</li>
          <li>Back-test: average error per state against synthetic “true” costs generated with the same formula plus noise, so it checks the code, not the real world. No measured haze-damage figures exist; the published RM 20–50 m a day is the outside check.</li>
          <li>Haze priority (Resource routing) weighs vulnerable people, not money: a high-cost state is not always first in line.</li>
        </ul>
        {att && <AttributionMethod att={att} />}
        <p className="hint">Placeholders are clearly marked values the team still has to replace with official figures; approximate values
          are reasoned from published totals. Every range below feeds the best/worst cases and the Monte Carlo. {dmg._note}</p>

        <h4>Costs and rates</h4>
        <div className="ledger-tbl-wrap">
          <table className="ledger-tbl">
            <thead><tr><th>Input</th><th className="r">Value</th><th className="r">Range</th><th>Unit</th><th>Source</th></tr></thead>
            <tbody>
              {coef.map(a => (
                <tr key={a.name}>
                  <td><b>{coefLabel(a.name)}</b><div className="mono hint">{a.name}</div></td>
                  <td className="r num">{fmtV(a)}</td>
                  <td className="r num">{a.range[0] === a.range[1] ? 'fixed' : `${num3(a.range[0])}–${num3(a.range[1])}`}</td>
                  <td>{a.unit}</td>
                  <td><Q src={a.source} /> {linkify(cleanSource(a.source)) }</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        <h4>Share of each sector's daily activity lost, by air-quality band</h4>
        <div className="ledger-tbl-wrap">
          <table className="ledger-tbl">
            <thead><tr><th>Sector</th>{Object.keys(BAND_LABEL).map(b => <th key={b} className="r">{BAND_LABEL[b]}</th>)}<th>Source</th></tr></thead>
            <tbody>
              {Object.entries(rates).map(([k, r]) => (
                <tr key={k}>
                  <td><b>{SECTOR[k] ? SECTOR[k].label : r.label}</b></td>
                  {Object.keys(BAND_LABEL).map(b => (
                    <td key={b} className="r num">{pct(r[b][1], r[b][1] < 0.01 && r[b][1] > 0 ? 1 : 0)}
                      <div className="hint">{pct(r[b][0], r[b][0] < 0.01 && r[b][0] > 0 ? 1 : 0)}–{pct(r[b][2], r[b][2] < 0.01 && r[b][2] > 0 ? 1 : 0)}</div></td>
                  ))}
                  <td><Q src={r.source} /> {linkify(cleanSource(r.source))}</td>
                </tr>
              ))}
              <tr><td><b>{SECTOR.health.label}</b></td><td colSpan={4} className="hint">Extra clinic visits and admissions from PM2.5 above 15 µg/m³ × unit costs (see above)</td><td>Dose-response</td></tr>
            </tbody>
          </table>
        </div>

        <h4>Data and method</h4>
        <div className="ledger-tbl-wrap">
          <table className="ledger-tbl">
            <thead><tr><th>Item</th><th>Value</th><th>Source</th></tr></thead>
            <tbody>
              {other.map(a => (
                <tr key={a.name}>
                  <td><b>{coefLabel(a.name)}</b><div className="mono hint">{a.name}</div></td>
                  <td>{fmtV(a)}{a.unit && typeof a.value === 'number' ? ` ${a.unit}` : ''}</td>
                  <td><Q src={a.source} /> {linkify(cleanSource(a.source))}</td>
                </tr>
              ))}
              <tr><td><b>Scenarios</b></td><td colSpan={2}>
                {SCEN.map(s => <div key={s.k}><b>{s.label}:</b> {v.scen[s.k].label}</div>)}
              </td></tr>
            </tbody>
          </table>
        </div>
        <p className="hint ledger-credit">
          Data: DOSM GDP by State 2025 and tourism receipts; OpenDOSM / data.gov.my (CC BY 4.0) · PM2.5: Copernicus CAMS via Open-Meteo (CC BY 4.0) ·
          Fire hotspots: NASA FIRMS · Model: <span className="mono">pipeline/04_policy.py</span>.
        </p>
      </div>
    </details>
  )
}
