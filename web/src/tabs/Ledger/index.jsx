/* ---------- derived view model ---------- */
function derive(dmg, eq) {
  const scen = dmg.forecast_72h.scenarios
  const nat = dmg.national
  const states = dmg.states
  const stateBy = Object.fromEntries(states.map(s => [s.state, s]))
  const statesSorted = [...states].sort((a, b) => b.forecast_72h_scenarios_rm.expected - a.forecast_72h_scenarios_rm.expected)
  const stMax = niceMax(Math.max(...states.map(s => s.forecast_72h_scenarios_rm.worst)) * 1.02)
  const sectorRows = SECTORS.map(s => ({
    ...s, best: scen.best.by_sector_rm[s.k], expected: scen.expected.by_sector_rm[s.k], worst: scen.worst.by_sector_rm[s.k],
    sofar: nat.by_category_rm[s.k],
  })).sort((a, b) => b.expected - a.expected)
  const secMax = niceMax(Math.max(...sectorRows.map(r => r.worst)) * 1.02)
  const winVals = Object.fromEntries(['24', '48', '72'].map(h => [h, Object.fromEntries(states.map(s => [s.state, s.forecast_damage_rm[h]]))]))
  const flatH = states.every(s => s.forecast_damage_rm['24'] === s.forecast_damage_rm['48'] && s.forecast_damage_rm['48'] === s.forecast_damage_rm['72'])
  const prio = {}
  if (eq && eq.states) for (const s of eq.states) prio[s.state] = s
  const b = dmg.model.benchmark_rm_per_day
  const persist = /persistence/i.test(dmg.forecast_72h.source || '')
  const nAssume = dmg.assumptions.length
  const nPlace = dmg.assumptions.filter(a => quality(a.source) === 'placeholder').length
  return {
    scen, nat, stateBy, statesSorted, stMax, sectorRows, secMax, winVals, flatH, prio, persist, nAssume, nPlace,
    bench72: b ? [b[0] * 3, b[1] * 3] : null,
    inBench: b ? nat.damage_per_day_rm >= b[0] && nat.damage_per_day_rm <= b[1] : false,
  }
}

/* ---------- selected state ---------- */
function StateDetail({ s, scen, prio, daily, picked, total }) {
  if (!s) return null
  const r = s.forecast_72h_scenarios_rm
  const top = SECTORS.map(x => [x, s.by_category_rm[x.k] || 0]).sort((a, b) => b[1] - a[1]).filter(([, v]) => v > 0).slice(0, 3)
  const series = daily && daily.by_state_rm && daily.by_state_rm[s.state]
  const alloc = prio && prio.allocation
  return (
    <div className="ledger-det" aria-live="polite">
      <div className="ledger-det-h">
        <div>
          <div className="label">{picked ? 'Selected state' : 'Highest expected damage'}</div>
          <h4>{short(s.state)}</h4>
        </div>
        <div className="ledger-det-big">
          <b className="num">{rm(r[scen])}</b>
          <small>{rm(r.best)} – {rm(r.worst)} next 72 h</small>
        </div>
      </div>
      <dl className="ledger-kv ledger-kv-3">
        <div><dt>So far</dt><dd className="num">{rm(s.damage_to_date_rm)}</dd></div>
        <div><dt>Share of national</dt><dd className="num">{pct(s.damage_to_date_rm / total, 0)}</dd></div>
        <div><dt>Of state GDP</dt><dd className="num">{s.damage_pct_gdp.toFixed(2)}%</dd></div>
      </dl>
      <div>
        <div className="ledger-det-l"><span className="label">Damage so far by sector</span></div>
        <SectorBar by={s.by_category_rm} />
        <div className="ledger-legend ledger-legend-sm">
          {top.map(([x, val]) => <span key={x.k}><i style={{ background: x.c }} />{x.label} {rm(val)}</span>)}
        </div>
      </div>
      {series && (
        <div>
          <div className="ledger-det-l"><span className="label">Damage per day so far</span></div>
          <Spark data={series} dates={daily.dates} />
        </div>
      )}
      {prio && (
        <p className="ledger-det-eq">
          <b>Haze priority #{prio.priority} of 16</b>
          {alloc ? <> · {alloc.mobile_clinic ? 'mobile clinic' : 'no mobile clinic'}{alloc.n95 ? ` · ${nf(alloc.n95)} N95` : ''}</> : null}
        </p>
      )}
    </div>
  )
}

