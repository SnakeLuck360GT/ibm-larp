/* ---------- assumptions ---------- */
function firePressureNote(fire) {
  const sh = fire && fire.forecast_importance_share && Object.values(fire.forecast_importance_share)
  const imp = sh && sh.length ? (Math.min(...sh) === Math.max(...sh) ? pct(sh[0]) : `${pct(Math.min(...sh))}–${pct(Math.max(...sh))}`) : null
  return `Upwind fire pressure: NASA FIRMS hotspots weighted by intensity, by how directly the local wind carries them to the state, and by distance; one of the haze team's forecast model inputs${imp ? ` (fire features carry ${imp} of its feature importance)` : ''}. Latest season in the processed data is the 2019 haze; counts fires in Malaysia as well as Indonesia.`
}

